#
# lk4pro_version.py
#
# tx3m - Version and firmware file name for the Longer LK4 Pro fork (env:LK4Pro).
#
#  - Version V<N>: the newest "V<N>" (or "v<N>") tag on this branch, plus the number of commits on
#    this branch since that tag. Only first-parent commits count, so merging official
#    Marlin counts as one commit. "-dev" is added if tracked files have uncommitted changes.
#  - Passed to the build as LKPro_FW_VERSION ("tx3mV<N>"), shown on the screen.
#  - After the build, firmware.hex is copied to "<Marlin version>_V<N>_<model>.hex",
#    e.g. "bugfix-2.1.x_V26_LK4Pro.hex", or "..._LK4Pro-SilentE.hex" with the silent E driver.
#    A copy of every build is kept in .pio/firmware (a later build of the same version replaces it).
#
#  Without git or a "v<N>" tag, the LKPro_FW_VERSION from Configuration.h is used.
#
import pioutil
if pioutil.is_pio_build():
    import re, shutil, subprocess
    from pathlib import Path
    Import("env")

    project_dir = Path(env['PROJECT_DIR'])

    def git(*args):
        return subprocess.run(['git', *args], cwd=project_dir, capture_output=True, text=True, check=True).stdout.strip()

    def config_value(path, pattern, default):
        match = re.search(pattern, (project_dir / path).read_text(encoding='utf-8', errors='ignore'), re.M)
        return match.group(1) if match else default

    def git_version():
        """'V<N>' or 'V<N>-dev', or None without git or a v<N> tag."""
        try:
            tag = git('describe', '--tags', '--abbrev=0', '--first-parent', '--match', 'v[0-9]*', '--match', 'V[0-9]*')
            count = int(git('rev-list', '--count', '--first-parent', f'{tag}..HEAD'))
            # Config-export.h is regenerated by every build, so it doesn't count as a change
            changed = git('status', '--porcelain', '--untracked-files=no', '--', '.', ':(exclude)Marlin/Config-export.h')
        except (OSError, subprocess.CalledProcessError, ValueError):
            return None
        return f'V{int(tag[1:]) + count}' + ('-dev' if changed else '')

    version = git_version()
    if version:
        env.Append(CPPDEFINES=[('LKPro_FW_VERSION', env.StringifyMacro('tx3m' + version))])
    else:
        fallback = config_value('Marlin/Configuration.h', r'^\s*#define\s+LKPro_FW_VERSION\s+"([^"]*)"', '')
        version = fallback.replace('tx3m', '') or 'unknown'
        print(f'lk4pro_version: no git version found, using "{fallback}" from Configuration.h')

    marlin_version = config_value('Marlin/src/inc/Version.h', r'^\s*#define\s+SHORT_BUILD_VERSION\s+"([^"]+)"', 'marlin')
    model = config_value('Marlin/Configuration.h', r'^\s*#define\s+(LK4_Pro|LK5_Pro)\b', 'LKPro').replace('_', '')
    # Silent E driver: set by env:LK4Pro_SilentE or enabled in Configuration.h
    silent_e = 'LKPro_SILENT_E_DRIVER' in str(env.GetProjectOption('build_flags', '')) \
            or config_value('Marlin/Configuration.h', r'^\s*#define\s+(LKPro_SILENT_E_DRIVER)\b', None)
    if silent_e: model += '-SilentE'
    # Input shaping: enabled in Configuration_adv.h
    if config_value('Marlin/Configuration_adv.h', r'^\s*#define\s+(INPUT_SHAPING_[XYZ])\b', None): model += '-IS'
    hex_name = f'{marlin_version}_{version}_{model}.hex'

    def copy_hex(source, target, env):
        build_dir = Path(env.subst('$BUILD_DIR'))
        shutil.copyfile(build_dir / 'firmware.hex', build_dir / hex_name)
        # Keep every version in .pio/firmware, since the build folder is cleaned when the configuration changes
        archive_dir = project_dir / '.pio' / 'firmware'
        archive_dir.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(build_dir / 'firmware.hex', archive_dir / hex_name)
        print(f'Firmware: {build_dir / hex_name}')
        print(f'Archived: {archive_dir / hex_name}')

    print(f'lk4pro_version: building {"tx3m" + version}')
    env.AddPostAction('$BUILD_DIR/${PROGNAME}.hex', copy_hex)
